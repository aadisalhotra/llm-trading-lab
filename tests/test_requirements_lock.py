"""The production lock stays a lock (hub ruling 2026-10-24: production does not
float).

requirements.txt is generated by scripts/lock_requirements.py from
requirements.in. These checks catch the ways it can quietly stop being one:
a floor or range re-added by hand, a direct dependency added to
requirements.in without regenerating, or a workflow going back to a floating
install. They do not re-resolve (that needs the network); regenerating is a
deliberate act.
"""
from __future__ import annotations

import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PIN = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)==([A-Za-z0-9.+!-]+)$")
PRODUCTION_WORKFLOWS = ("intraday.yml", "competitor_monitor.yml", "tests.yml")


def _canon(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def _requirement_lines(path: str) -> list[str]:
    with open(os.path.join(ROOT, path), encoding="utf-8") as f:
        return [ln.strip() for ln in f if ln.strip() and not ln.strip().startswith("#")]


def test_every_lock_line_is_an_exact_pin():
    lines = _requirement_lines("requirements.txt")
    bad = [ln for ln in lines if not PIN.match(ln)]
    assert not bad, f"not an exact name==version pin: {bad}"
    names = [_canon(PIN.match(ln).group(1)) for ln in lines]
    assert len(names) == len(set(names)), "a package is pinned twice"


def test_lock_covers_every_direct_dependency():
    locked = {_canon(PIN.match(ln).group(1)) for ln in _requirement_lines("requirements.txt")}
    direct = {_canon(re.split(r"[<>=!~;\[ ]", ln, maxsplit=1)[0])
              for ln in _requirement_lines("requirements.in")}
    missing = sorted(direct - locked)
    assert not missing, f"in requirements.in but not locked (regenerate): {missing}"


def test_production_workflows_install_the_lock_without_floating():
    for name in PRODUCTION_WORKFLOWS:
        with open(os.path.join(ROOT, ".github", "workflows", name), encoding="utf-8") as f:
            text = f.read()
        assert "pip install --no-deps -r requirements.txt" in text, name
        assert "pip check" in text, name
        assert "--upgrade pip" not in text, f"{name}: pip floats"
        assert not re.search(r'pip install [^\n]*"[A-Za-z_-]+>=', text), f"{name}: a floor install"
